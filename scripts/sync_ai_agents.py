#!/usr/bin/env python3
"""Generate provider adapters from the portable OA/ERP team instructions."""
import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parent.parent
MARKER = 'Generated by scripts/sync_ai_agents.py; edit ai/ sources instead.'
FIELDS = {'id', 'role_file', 'codex_name', 'claude_name', 'description'}


def build_outputs() -> dict[Path, str]:
    entries = json.loads((ROOT / 'ai/agents.json').read_text())
    common = (ROOT / 'ai/GLOBAL_INSTRUCTIONS.md').read_text().strip()
    if not isinstance(entries, list) or not entries or not common:
        raise ValueError('Expected a nonempty agent catalog and global instructions')
    seen = {key: set() for key in ('id', 'codex_name', 'claude_name', 'role_file')}
    outputs = {}
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != FIELDS:
            raise ValueError('Unexpected or missing agent catalog fields')
        if any(not isinstance(value, str) or not value.strip() for value in entry.values()):
            raise ValueError('Agent catalog values must be nonempty strings')
        for key, pattern in [('id', r'[A-Z]{2}-[0-9]{2}'),
                             ('codex_name', r'[a-z][a-z0-9_]*'),
                             ('claude_name', r'[a-z][a-z0-9-]*')]:
            if not re.fullmatch(pattern, entry[key]):
                raise ValueError(f'Invalid {key}: {entry[key]}')
        for key in seen:
            if entry[key] in seen[key]:
                raise ValueError(f'Duplicate {key}: {entry[key]}')
            seen[key].add(entry[key])
        role_path = (ROOT / entry['role_file']).resolve()
        if not role_path.is_relative_to((ROOT / 'ai/agents').resolve()) or role_path.suffix != '.md':
            raise ValueError('Role source must be a Markdown file inside ai/agents')
        role = role_path.read_text().strip()
        if not role:
            raise ValueError(f'Empty role instructions: {role_path}')
        prompt = common + '\n\n' + role + '\n'
        if "'''" in prompt:
            raise ValueError('TOML literal delimiter is not allowed in source instructions')
        quote = lambda value: json.dumps(value, ensure_ascii=False)
        codex = (f'# {MARKER}\nname = {quote(entry["codex_name"])}\n'
                 f'description = {quote(entry["description"])}\n'
                 f"developer_instructions = '''\n{prompt}'''\n")
        parsed = tomllib.loads(codex)
        if parsed['developer_instructions'] != prompt:
            raise ValueError('TOML roundtrip changed the instructions')
        claude = ('---\n' + f'name: {entry["claude_name"]}\n'
                  f'description: {quote(entry["description"])}\n'
                  'isolation: worktree\n')
        if entry['id'] == 'CR-01':
            # Bash is retained for checks; prompt-level independence is not a sandbox.
            claude += 'tools: Read, Grep, Glob, Bash\n'
        claude += f'---\n\n<!-- {MARKER} -->\n\n{prompt}'
        outputs[ROOT / f'.codex/agents/{entry["codex_name"]}.toml'] = codex
        outputs[ROOT / f'.claude/agents/{entry["claude_name"]}.md'] = claude
    return outputs


def validate_destination(path: Path) -> None:
    # Do not follow shared/global configurations through a repository symlink.
    if not path.resolve().is_relative_to(ROOT):
        raise ValueError(f'Adapter destination escapes the repository: {path.relative_to(ROOT)}')
    current = ROOT
    for part in path.relative_to(ROOT).parts:
        current = current / part
        if current.is_symlink():
            raise ValueError(f'Symlink adapter destinations are not supported: {current.relative_to(ROOT)}')


def orphan_adapters(outputs: dict[Path, str]) -> list[Path]:
    expected = set(outputs)
    orphans = []
    for folder, pattern in [('.codex/agents', '*.toml'), ('.claude/agents', '*.md')]:
        for path in (ROOT / folder).glob(pattern):
            # Unknown symlinks belong to the user, not this generator. Never follow them.
            if path in expected or path.is_symlink() or not path.is_file():
                continue
            if MARKER in path.read_text():
                orphans.append(path.relative_to(ROOT))
    return sorted(orphans)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--check', action='store_true', help='Check adapters without writing files')
    modes.add_argument('--adopt-existing', action='store_true', help='Explicitly replace hand-written adapters at catalog paths')
    args = parser.parse_args()
    try:
        outputs = build_outputs()
        for path in outputs:
            validate_destination(path)
        orphans = orphan_adapters(outputs)
        if orphans:
            raise ValueError('Orphan generated adapters require reviewed cleanup: ' + ', '.join(map(str, orphans)))
        changed = [path for path, value in outputs.items() if not path.exists() or path.read_text() != value]
        if args.check:
            for path in changed:
                print(f'STALE: {path.relative_to(ROOT)}')
            print(f'{len(outputs)} adapters checked; {len(changed)} stale')
            return 1 if changed else 0
        # Preflight all destinations: a refusal must not leave a partially updated set.
        for path in changed:
            if path.exists() and MARKER not in path.read_text() and not args.adopt_existing:
                raise ValueError(f'Refusing to replace hand-written {path.relative_to(ROOT)}; review it or use --adopt-existing')
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path])
            print(f'UPDATED: {path.relative_to(ROOT)}')
        print(f'{len(outputs)} adapters; {len(changed)} updated')
        return 0
    except (ValueError, OSError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
