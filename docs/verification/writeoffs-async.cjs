const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const {context,state,photo}=require('./writeoffs-smoke.cjs');
const deferred=()=>{let release;const promise=new Promise(resolve=>{release=resolve});return{promise,release}};
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const shared=state('draft',[photo()]),{ctx,page,root,errors}=await context(browser,shared);
  const gate=deferred();shared.detailGate=gate.promise;
  const pending=page.waitForRequest(r=>r.url().includes('warehouse/writeoffs?')&&new URL(r.url()).searchParams.has('id'));
  await root.getByRole('button',{name:'Открыть',exact:true}).click();await pending;
  await root.getByLabel(/^Статус/).selectOption('approved');gate.release();await page.waitForTimeout(500);
  assert.equal(await root.locator('#writeoff-details').count(),0,'Late details cannot reopen after filtering');
  await root.getByLabel(/^Статус/).selectOption('');
  await root.getByRole('button',{name:'Открыть',exact:true}).click();
  const photoGate=deferred();shared.photoGate=photoGate.promise;
  const photoPending=page.waitForRequest(r=>r.url().endsWith('/photos/1/download'));
  await root.getByRole('button',{name:'Показать фотографию 1',exact:true}).click();await photoPending;
  await root.getByRole('button',{name:'Закрыть детали',exact:true}).click();
  photoGate.release();await page.waitForTimeout(500);
  assert.equal(await page.evaluate(()=>window.__photoUrls.live.size),0,'No object URL is retained from a closed pending preview');
  assert.equal(await root.locator('img').count(),0);
  await root.getByRole('button',{name:'Открыть',exact:true}).click();
  await root.getByRole('button',{name:'Показать фотографию 1',exact:true}).click();
  await page.waitForFunction(()=>window.__photoUrls.live.size>0);
  shared.revoked=true;
  await root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await root.getByRole('alert').waitFor();
  await page.waitForFunction(()=>window.__photoUrls.live.size===0);
  assert.equal(await root.locator('#writeoff-details').count(),0,'Revocation removes evidence and actions');
  assert.equal(errors.length,0,JSON.stringify(errors));await ctx.close();
  const retryState=state('posted',[photo()]),retry=await context(browser,retryState);
  retryState.outsidePage=true;retryState.movements=true;
  await retry.root.getByRole('button',{name:'Движения',exact:true}).click();
  await retry.root.getByRole('button',{name:'Открыть',exact:true}).click();
  await retry.root.locator('#writeoff-details').waitFor();
  retryState.detailFailure=true;
  await retry.root.getByRole('button',{name:'Движения',exact:true}).click();
  await retry.root.getByRole('button',{name:'Открыть',exact:true}).click();
  await retry.root.getByRole('alert').waitFor();
  retryState.detailFailure=false;
  await retry.root.getByRole('button',{name:'Повторить',exact:true}).click();
  await retry.root.locator('#writeoff-details').waitFor();
  assert((await retry.root.locator('#writeoff-details').innerText()).includes('WO-TEST'));
  retryState.revoked=true;
  await retry.root.getByRole('button',{name:'Показать фотографию 1',exact:true}).click();
  await retry.root.getByRole('alert').waitFor();
  assert.equal(await retry.root.locator('#writeoff-details').count(),0,'Private download403 clears document access');
  assert.equal(retry.errors.length,0,JSON.stringify(retry.errors));await retry.ctx.close();
  console.log(JSON.stringify({result:'PASS',flows:['late details ignored after filter','aborted private photo cannot recreate blob after closing','revoked rights remove existing blob and actions','initial exact ledger document loads in StrictMode','exact ledger document retry after500 outside list page','private photo403 clears stale document'],errors:[]}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
