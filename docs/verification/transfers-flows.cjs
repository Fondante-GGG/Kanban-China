const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const {context,state,axeCheck}=require('./transfers-smoke.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try {
  const shared=state();
  const sender=await context(browser,shared,'sender');
  const {root,page}=sender;
  await root.getByRole('button',{name:'Новое перемещение',exact:true}).click();
  const form=root.locator('form');
  await form.getByLabel('Номер перемещения',{exact:true}).fill('TR-BROWSER');
  await form.getByLabel(/^Склад назначения/).selectOption('2');
  await form.getByLabel(/^Товар \/ SKU/).selectOption('1');
  await form.getByLabel(/^Ячейка источника/).selectOption('10');
  await form.getByLabel(/^Ячейка назначения/).selectOption('20');
  await form.getByLabel(/^Партия/).selectOption('BATCH-1');
  await form.getByLabel('Количество',{exact:true}).fill('3');
  assert.equal((await axeCheck(page)).length,0,'Sender form accessibility');
  await form.getByRole('button',{name:'Сохранить черновик',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).waitFor();
  const payload=shared.calls.find(c=>c.path==='warehouse/transfers').body;
  assert.equal(payload.source_warehouse_id,1);assert.equal(payload.destination_warehouse_id,2);
  assert.equal(payload.items[0].source_location_id,10);assert.equal(payload.items[0].destination_location_id,20);
  assert.equal(payload.items[0].batch_no,'BATCH-1');assert(!('unit_cost' in payload.items[0]));
  assert.equal(await root.getByRole('button',{name:'Согласовать',exact:true}).count(),0,'Sender cannot approve own transfer');
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.sourceQty,10);assert.equal(shared.destQty,0);
  const reviewer=await context(browser,shared,'reviewer');
  await reviewer.root.getByRole('button',{name:'Открыть',exact:true}).click();
  await reviewer.root.getByRole('button',{name:'Вернуть на доработку',exact:true}).click();
  await reviewer.root.getByRole('alert').waitFor();
  assert.equal(shared.transfer.status,'pending_approval','Return requires a reason');
  await reviewer.root.getByLabel('Причина решения',{exact:true}).fill('Уточнить количество');
  await reviewer.root.getByRole('button',{name:'Вернуть на доработку',exact:true}).click();
  await reviewer.root.getByRole('button',{name:'Согласовать',exact:true}).waitFor({state:'hidden'});
  await root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await root.getByRole('button',{name:'Редактировать',exact:true}).waitFor();
  await root.getByRole('button',{name:'Редактировать',exact:true}).click();
  assert(await form.getByLabel('Номер перемещения',{exact:true}).isEditable()===false);
  assert(await form.getByLabel(/^Склад назначения/).isDisabled());
  await form.getByLabel('Комментарий',{exact:true}).fill('Исправлено');
  await form.getByRole('button',{name:'Сохранить черновик',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).waitFor({state:'hidden'});
  await reviewer.root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await reviewer.root.getByRole('button',{name:'Согласовать',exact:true}).click();
  await reviewer.root.getByRole('button',{name:'Согласовать',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.sourceQty,10);assert.equal(shared.destQty,0);
  await root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await root.getByRole('button',{name:'Подтвердить отправку',exact:true}).click();
  await root.getByRole('button',{name:'Подтвердить',exact:true}).click();
  await root.getByRole('button',{name:'Подтвердить',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.sourceQty,7);assert.equal(shared.destQty,0);assert.equal(shared.transfer.in_transit_qty,'3');
  assert.equal(await root.getByRole('button',{name:'Подтвердить получение',exact:true}).count(),0,'Sender cannot receive');
  const receiver=await context(browser,shared,'receiver');
  await receiver.root.getByRole('button',{name:'Открыть',exact:true}).click();
  assert.equal(await receiver.root.getByRole('button',{name:'Подтвердить отправку',exact:true}).count(),0,'Receiver cannot dispatch');
  await receiver.root.getByRole('button',{name:'Подтвердить получение',exact:true}).click();
  assert.equal((await axeCheck(receiver.page)).length,0,'Receive confirmation accessibility');
  await receiver.root.getByRole('button',{name:'Подтвердить',exact:true}).click();
  await receiver.root.getByRole('button',{name:'Подтвердить',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.sourceQty,7);assert.equal(shared.destQty,3);assert.equal(shared.transfer.in_transit_qty,'0');
  shared.revoked=true;
  await receiver.root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await receiver.root.getByRole('alert').waitFor();
  assert.equal(await receiver.root.getByRole('button',{name:'Подтвердить получение',exact:true}).count(),0);
  console.log(JSON.stringify({result:'PASS',posts:shared.calls.length,flows:['create with locations and batch','return requires reason','edit immutable route','independent approval','dispatch confirmation','transit separate from physical','destination receive confirmation','revoked rights'],errors:[...sender.errors,...reviewer.errors,...receiver.errors]}));
  assert.equal([...sender.errors,...reviewer.errors,...receiver.errors].length,0);
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
