const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const {context,state,png,axeCheck}=require('./writeoffs-smoke.cjs');
const imageFile={name:'evidence.png',mimeType:'image/png',buffer:png};
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const shared=state(),operator=await context(browser,shared),{root,page}=operator;
  await root.getByRole('button',{name:'Новое списание',exact:true}).click();
  const form=root.locator('form');
  await form.getByLabel('Номер списания',{exact:true}).fill('WO-BROWSER');
  await form.getByLabel('Причина списания',{exact:true}).fill('Истёк срок годности');
  await form.getByLabel(/^Товар \/ SKU/).selectOption('1');
  await form.getByLabel(/^Ячейка/).selectOption('10');
  await form.getByLabel(/^Партия/).selectOption('BATCH-1');
  await form.getByLabel('Количество',{exact:true}).fill('1.25');
  assert.equal((await axeCheck(page)).length,0,'Draft accessibility');
  await form.getByRole('button',{name:'Сохранить черновик',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).waitFor();
  assert(await root.getByRole('button',{name:'Передать на согласование',exact:true}).isDisabled(),'Saved draft needs a server photo');
  await root.getByLabel('Добавить фотографию',{exact:true}).setInputFiles({name:'bad.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg/>')});
  await root.getByRole('alert').waitFor();assert.equal(shared.calls.length,1,'Invalid local type never uploads');
  await root.getByLabel('Добавить фотографию',{exact:true}).setInputFiles(imageFile);
  assert(await root.getByRole('button',{name:'Передать на согласование',exact:true}).isDisabled(),'Selected local file is not uploaded evidence');
  shared.failNextUpload=true;
  await root.getByRole('button',{name:'Загрузить фотографию',exact:true}).click();
  await root.getByRole('alert').waitFor();
  assert.equal(shared.doc.photos.length,0,'Server rejection must not create evidence');
  assert.equal(await root.getByLabel('Добавить фотографию',{exact:true}).evaluate(input=>input.files[0].name),'evidence.png','Rejected upload retains local file for retry');
  await root.getByRole('button',{name:'Загрузить фотографию',exact:true}).click();
  await root.getByRole('button',{name:'Показать фотографию 1',exact:true}).waitFor();
  assert(shared.calls.find(c=>c.path.endsWith('/photos')).multipartContainsPng,'Multipart carries actual image bytes');
  assert.match(shared.calls.find(c=>c.path.endsWith('/photos')).headers['content-type'],/^multipart\/form-data;/);
  await root.getByRole('button',{name:'Показать фотографию 1',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('main section img')].some(i=>i.complete&&i.naturalWidth>0&&i.src.startsWith('blob:')));
  assert(shared.downloads.every(d=>d.authorization==='Bearer operator'));
  const download=root.getByRole('link',{name:'Скачать фотографию',exact:true});
  assert((await download.getAttribute('href')).startsWith('blob:'),'Download does not expose a public media path');
  await root.getByRole('button',{name:'Закрыть детали',exact:true}).click();
  await page.waitForFunction(()=>window.__photoUrls.live.size===0);
  await root.getByRole('button',{name:'Открыть',exact:true}).click();
  await root.getByRole('button',{name:'Убрать из черновика фотографию 1',exact:true}).click();
  await root.getByRole('button',{name:'Убрать из черновика',exact:true}).click();
  await root.getByRole('button',{name:'Показать фотографию 1',exact:true}).waitFor({state:'hidden'});
  assert(await root.getByRole('button',{name:'Передать на согласование',exact:true}).isDisabled());
  await root.getByLabel('Добавить фотографию',{exact:true}).setInputFiles(imageFile);
  await root.getByRole('button',{name:'Загрузить фотографию',exact:true}).click();
  await root.getByRole('button',{name:'Показать фотографию 1',exact:true}).waitFor();
  assert.equal(await root.getByRole('button',{name:'Согласовать',exact:true}).count(),0,'Author cannot approve');
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.stock,'10.500');
  assert.equal(await root.getByLabel('Добавить фотографию',{exact:true}).count(),0,'Submitted evidence is locked');
  const reviewer=await context(browser,shared,'reviewer');
  await reviewer.root.getByRole('button',{name:'Открыть',exact:true}).click();
  await reviewer.root.getByRole('button',{name:'Вернуть на доработку',exact:true}).click();
  await reviewer.root.getByRole('alert').waitFor();assert.equal(shared.doc.status,'pending_approval');
  await reviewer.root.getByLabel('Причина решения',{exact:true}).fill('Уточнить причину');
  await reviewer.root.getByRole('button',{name:'Вернуть на доработку',exact:true}).click();
  await reviewer.root.getByRole('button',{name:'Согласовать',exact:true}).waitFor({state:'hidden'});
  await root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).click();
  await root.getByRole('button',{name:'Передать на согласование',exact:true}).waitFor({state:'hidden'});
  await reviewer.root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await reviewer.root.getByRole('button',{name:'Согласовать',exact:true}).click();
  await reviewer.root.getByRole('button',{name:'Согласовать',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.stock,'10.500','Approval must not reduce physical stock');
  await root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await root.getByRole('button',{name:'Провести списание',exact:true}).click();
  assert.equal((await axeCheck(page)).length,0,'Post confirmation accessibility');
  await root.getByRole('button',{name:'Подтвердить списание',exact:true}).click();
  await root.getByRole('button',{name:'Подтвердить списание',exact:true}).waitFor({state:'hidden'});
  assert.equal(shared.stock,'9.25');assert.equal(shared.doc.status,'posted');
  assert.equal(await root.getByLabel('Добавить фотографию',{exact:true}).count(),0);
  shared.revoked=true;await root.getByRole('button',{name:'Обновить',exact:true}).last().click();
  await root.getByRole('alert').waitFor();assert.equal(await root.locator('#writeoff-details').count(),0);
  assert.equal(operator.errors.length+reviewer.errors.length,0);
  console.log(JSON.stringify({result:'PASS',mutations:shared.calls.length,flows:['fractional draft with batch/location','invalid local file rejected','local selection does not enable submit','actual multipart upload','authenticated private blob preview/download','object URL cleanup','softremove needs new evidence','independent review with reason','evidence frozen outside draft','post confirmation reduces stock','revoked access'],errors:[...operator.errors,...reviewer.errors]}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
